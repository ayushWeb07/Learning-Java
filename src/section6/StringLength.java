package section6;

public class StringLength {
    public static void main(String[] args) {
        String a= "M5";
        String b= "is";
        String c= "my love";
        String d= a + " " + b + " " + c;

        int aL= a.length();
        int bL= b.length();
        int cL= c.length();
        int dL= d.length();

        System.out.println(aL);
        System.out.println(bL);
        System.out.println(cL);
        System.out.println(dL);
    }
}
